#!/usr/bin/env ruby
# The URL move: guide pages go from /caching to /learn/caching, API symbols from
# /up.render to /api/up.render.
#
# The site's model decides where every document lives (Documentable#guide_path, Toc).
# Slugs in the Unpoly sources ([[wikilinks]], @learn-ref, toc.yml) follow it on their
# own. This script handles what the model cannot reach, in the Unpoly repository next
# to this one (vendor/unpoly-local):
#
# 1. Links written as URLs are rewritten to the new paths: Markdown links
#    `[label](/up.render)`, `href="/caching"` in prose, `[[=base_url]]/up.render.md`
#    and `https://unpoly.com/caching` anywhere, as well as `unpoly.com/caching` spelled
#    out as text (the README's link label). Code blocks and code spans are left
#    alone (examples are full of `href="/users"`), except for the site's own URLs,
#    which can only mean this site. In .js files, comments are rewritten, and outside
#    of them only full unpoly.com URLs (error messages); Unpoly and the site deploy
#    minutes apart.
#    Only paths of documents are touched; everything that stays at the root
#    (/changes, /support, /images, ...) and every unknown path is left alone and
#    listed.
#
# 2. Old paths need no redirect of their own: a general rule in source/.htaccess.erb
#    sends /foo to /learn/foo, else to /api/foo. The redirect block that earlier dry
#    runs generated at the top of src/unpoly-migrate/.htaccess is removed, and a note
#    there says where the old paths went. The script aborts when the short URLs
#    /install and /skill (printed on slides and in talks) would no longer resolve, or
#    when a hand-written redirect starts at a path that the general rule takes (Apache
#    applies the rule first, so the redirect would never fire).
#
# 3. The targets of the hand-written redirects (src/unpoly-migrate/.htaccess, and
#    source/.htaccess.erb here) are rewritten to their final page, following chains,
#    so that every old URL takes one hop.
#
# Running it twice changes nothing the second time.
#
#   bundle exec rake docs:url_move            # rewrite, print a summary
#   DRY_RUN=1 bundle exec rake docs:url_move  # only print what would change
#   VERBOSE=1 ...                             # also list every rewritten link

require 'set'

SITE_ROOT = File.expand_path('..', __dir__)
Dir.chdir(SITE_ROOT)

require File.join(SITE_ROOT, 'lib/unpoly/site')
Docs = Unpoly::Site

class UrlMove
  class Abort < StandardError; end

  # The block that earlier versions of this script generated, with one redirect per old
  # path. Removed on every run.
  BLOCK_BEGIN = '# BEGIN URL MOVE (generated by unpoly-site script/url_move.rb, do not edit by hand)'
  BLOCK_END = '# END URL MOVE'

  # Put at the top of src/unpoly-migrate/.htaccess.
  NOTE = <<~NOTE
    # Documents moved under /learn and /api in the docs rework 2026. Their old paths
    # (/caching, /up.render) need no rule here: unpoly-site's .htaccess redirects every
    # /foo to /learn/foo, else to /api/foo. Only renamed or removed pages go below.
    # Never redirect from a path that is also a document's slug: that rule would never fire.
  NOTE

  # Short URLs that people type from slides. They must always resolve.
  PERMANENT_SHORT_URLS = %w[/install /skill].freeze

  REDIRECT_LINE = /^(\s*RedirectPermanent\s+)(\S+)(\s+)(\S+)(\s*)$/

  def initialize(repository: Docs.current, write: true, verbose: false)
    @repository = repository
    @links = Docs::LegacyLinks.new(repository)
    @unpoly = @links.unpoly
    @write = write
    @verbose = verbose
    @rewritten = Hash.new { |hash, key| hash[key] = [] } # form => ["file: old -> new"]
    @kept = Hash.new(0)                                   # root path left alone => count
    @changed_files = []
  end

  def run
    check_model!
    rewrite_sources
    rewrite_redirects
    summary
  end

  # ---------- The model ----------

  # Every document's old path and its new one: "/up.render" => "/api/up.render".
  def moves
    @links.moves
  end

  def new_paths
    @new_paths ||= Set.new(moves.values)
  end

  # Pages the site itself implements (source/**/*.html.erb), which stay where they are.
  def site_paths
    @site_paths ||= Set.new(
      Dir['source/**/*.html.erb'].filter_map { |file|
        path = file.delete_prefix('source/').delete_suffix('.html.erb').sub(%r{(\A|/)index\z}, '')
        next if File.basename(path).start_with?('_') || path.end_with?('_template')
        "/#{path}"
      } + ['/']
    )
  end

  def check_model!
    if moves.all? { |from, to| from == to }
      raise Abort, 'The site still serves documents at the root. Apply the site side of the URL move first (Documentable#guide_path).'
    end

    stuck = moves.select { |from, to| from == to }
    stuck.empty? or raise Abort, "Documents that would not move: #{stuck.keys.join(', ')}"

    # A page at the root wins over the general rule, so it would take a document's old path.
    taken = moves.keys.select { |from| site_paths.include?(from) || from.start_with?('/learn/', '/api/') }
    taken.empty? or raise Abort, "Old paths that the site still serves: #{taken.join(', ')}"

    clashes = site_paths & new_paths
    clashes.empty? or raise Abort, "New paths that clash with the site's own pages: #{clashes.to_a.join(', ')}"

    missing = PERMANENT_SHORT_URLS - moves.keys - hand_written_redirects.keys
    missing.empty? or raise Abort, "Short URLs that would no longer resolve: #{missing.join(', ')}"
  end

  # ---------- Links in the sources ----------

  def rewrite_sources
    @links.unpoly_files.each do |file, code_aware|
      text = File.read(file)
      @current_file = file.delete_prefix("#{@unpoly}/")
      new_text = @links.rewrite(text, file: file, code_aware: code_aware) do |form, path, moved|
        if moved
          @rewritten[form] << "#{@current_file}: #{path} -> #{moved}"
        elsif path != '/' && !path.start_with?('/learn/', '/api/') && form != 'href="/path" in prose'
          @kept[path] += 1
        end
      end
      save(file, new_text) if new_text != text
    end
  end

  # ---------- Redirects ----------

  def migrate_htaccess
    File.join(@unpoly, 'src/unpoly-migrate/.htaccess')
  end

  def site_htaccess
    File.join(SITE_ROOT, 'source/.htaccess.erb')
  end

  # The hand-written redirects, in the order Apache sees them: the site's own rules
  # come first in the .htaccess, the included migrate rules after them.
  def hand_written_redirects
    @hand_written_redirects ||= [site_htaccess, migrate_htaccess].flat_map { |file|
      strip_block(File.read(file)).lines.filter_map { |line| line.match(REDIRECT_LINE)&.values_at(2, 4) }
    }.reverse.to_h # the first rule for a path wins
  end

  # Where a redirect target ends up: a document's new path, a page the site serves,
  # or an external URL. Follows chains of hand-written redirects, so that each old URL
  # takes a single hop. Returns nil for a target that leads nowhere.
  def final_target(target, seen = Set.new)
    return target if target.include?('://')

    path, anchor = target.split('#', 2)
    return [moves[path], anchor].compact.join('#') if moves.key?(path)
    return target if new_paths.include?(path) || site_paths.include?(path)
    return nil if seen.include?(path) || !hand_written_redirects.key?(path)

    seen << path
    next_target = hand_written_redirects[path]
    # A redirect to an anchor keeps it; otherwise the next one's anchor applies.
    next_target = "#{next_target.split('#', 2).first}##{anchor}" if anchor
    final_target(next_target, seen)
  end

  def rewrite_redirects
    @unresolved = []
    @retargeted = []
    # Apache applies the .htaccess's RewriteRules (the general rule) before its
    # RedirectPermanent lines, so a redirect from a document's old path would never fire.
    shadowed = hand_written_redirects.keys.select { |from| moves.key?(from) }
    shadowed.empty? or raise Abort, "Hand-written redirects from a path that is also a document (delete them, the general rule takes these paths): #{shadowed.join(', ')}"

    [site_htaccess, migrate_htaccess].each do |file|
      @current_file = file
      text = strip_block(File.read(file))
      text = text.gsub(REDIRECT_LINE) do
        prefix, from, space, target, suffix = $1, $2, $3, $4, $5
        final = final_target(target)
        if final.nil?
          @unresolved << "#{from} -> #{target}"
          $&
        else
          @retargeted << "#{from}: #{target} -> #{final}" if final != target
          "#{prefix}#{from}#{space}#{final}#{suffix}"
        end
      end
      text = insert_note(text) if file == migrate_htaccess
      save(file, text) if text != File.read(file)
    end
  end

  # The note opens the file, after its own header comment.
  def insert_note(text)
    return text if text.include?(NOTE)

    header, rest = text.match(/\A((?:#[^\n]*\n|\s*\n)*)(.*)\z/m).captures
    "#{header.rstrip}\n\n#{NOTE}\n#{rest.lstrip}"
  end

  def strip_block(text)
    text.sub(/^#{Regexp.escape(BLOCK_BEGIN)}\n.*?^#{Regexp.escape(BLOCK_END)}\n+/m, '')
  end

  # ---------- Output ----------

  def save(file, text)
    @changed_files << file
    File.write(file, text) if @write
  end

  def summary
    puts(@write ? 'URL move' : 'URL move (dry run, nothing written)')
    puts
    puts "Documents moved: #{moves.size} (#{moves.count { |_, to| to.start_with?('/learn/') }} to /learn, #{moves.count { |_, to| to.start_with?('/api/') }} to /api)"
    puts "Old paths redirected by the general rule in source/.htaccess.erb: #{moves.size}"
    puts
    puts 'Links rewritten:'
    total = 0
    @rewritten.each do |form, entries|
      total += entries.size
      puts "  #{entries.size.to_s.rjust(5)}  #{form}"
    end
    puts "  #{total.to_s.rjust(5)}  in total"

    puts
    puts "Hand-written redirects retargeted: #{@retargeted.size}"
    @retargeted.each { |entry| puts "  #{entry}" } if @verbose
    puts "Files changed: #{@changed_files.size}"
    @changed_files.each { |file| puts "  #{file.delete_prefix("#{@unpoly}/").delete_prefix("#{SITE_ROOT}/")}" }

    unless @kept.empty?
      puts
      puts 'Root paths left alone (not a document):'
      @kept.sort.each { |path, count| puts "  #{path} (#{count})" }
    end

    if @verbose
      puts
      @rewritten.each do |form, entries|
        puts "#{form}:"
        entries.each { |entry| puts "  #{entry}" }
      end
    else
      puts
      puts 'href="/path" rewrites (check that none is an example):'
      @rewritten['href="/path" in prose'].each { |entry| puts "  #{entry}" }
    end

    unless @unresolved.empty?
      puts
      puts 'UNRESOLVED redirect targets (fix by hand):'
      @unresolved.each { |entry| puts "  #{entry}" }
      raise Abort, "#{@unresolved.size} redirect(s) lead nowhere."
    end
  end
end

if $PROGRAM_NAME == __FILE__
  begin
    UrlMove.new(write: !ENV['DRY_RUN'], verbose: !!ENV['VERBOSE']).run
  rescue UrlMove::Abort => e
    abort "URL move aborted: #{e.message}"
  end
end
